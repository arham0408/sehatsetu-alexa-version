import { test, expect } from '@playwright/test';

test('report → real MCP → answer → paired browser → verified anatomy → revocation', async ({ page, context }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/?demo=1');
  await expect(page.getByRole('region', { name: 'SehatSetu Medical Report Explorer' })).toBeVisible({ timeout: 60000 });
  await page.locator('.sehatsetu-sample-chip').first().click();
  await expect(page.locator('.sehatsetu-finding-card').first()).toBeVisible({ timeout: 30000 });
  await page.getByRole('tab', { name: 'Voice companion' }).click();
  await page.getByRole('button', { name: 'Connect report to assistant' }).click();
  await expect(page.getByText(/Connected ·/)).toBeVisible();
  await page.getByRole('button', { name: 'Show me the gallbladder', exact: true }).click();
  await expect(page.locator('.voice-answer').first()).toContainText('Report excerpts');
  await expect(page.getByText('Verified anatomy highlighted in the 3D viewer.')).toBeVisible({ timeout: 10000 });
  await page.getByText('MCP activity · reviewer view').click();
  await expect(page.locator('.voice-activity')).toContainText('initialize');
  await expect(page.locator('.voice-activity')).toContainText('tools/list');
  await expect(page.locator('.voice-activity')).toContainText('ask_report');
  await page.getByText(/Use another browser as the voice companion/).click();
  await page.getByRole('button', { name: 'Create companion invitation', exact: true }).click();
  const link = await page.getByRole('textbox', { name: 'Private invitation link' }).inputValue();
  const peer = await context.newPage();
  peer.on('pageerror', error => errors.push(error.message));
  await peer.goto(link);
  await expect(peer).toHaveURL(/\?companion=1$/);
  await peer.getByRole('button', { name: 'Join report session' }).click();
  await expect(peer.getByText(/Connected ·/)).toBeVisible();
  await peer.getByRole('textbox', { name: 'Ask about this report' }).fill('Show me the liver');
  await peer.getByRole('button', { name: 'Send question' }).click();
  await expect(peer.locator('.voice-answer').first()).toContainText('Report excerpts');
  await expect(peer.getByText('Location sent.', { exact: false })).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'Prepare questions for my doctor (English)' }).click();
  await expect(page.locator('.voice-answer').last()).toContainText('What does this mean for me');
  await page.getByText(/Use another browser as the voice companion/).click();
  await page.locator('.sehatsetu-body').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: 'outputs/hackathon-desktop.png', fullPage: true });
  await peer.setViewportSize({ width: 390, height: 844 });
  await peer.getByRole('button', { name: 'Send question' }).scrollIntoViewIfNeeded();
  await expect(peer.getByRole('button', { name: 'Send question' })).toBeInViewport();
  await peer.locator('.companion-page').evaluate(element => { element.scrollTop = 0; });
  await peer.screenshot({ path: 'outputs/hackathon-companion-mobile.png', fullPage: true });
  expect(await peer.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByText(/Use another browser as the voice companion/).click();
  await page.getByRole('button', { name: 'Revoke all companions and invitations' }).click();
  await expect(peer.getByRole('alert')).toContainText('Session unavailable', { timeout: 10000 });
  await page.getByRole('button', { name: 'Disconnect and delete report session' }).click();
  await expect(page.getByRole('button', { name: 'Connect report to assistant' })).toBeVisible();
  expect(errors).toEqual([]);
});
